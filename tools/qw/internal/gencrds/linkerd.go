package gencrds

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/quenchworks/charts/tools/qw/internal/core"
)

const linkerdBase = "https://raw.githubusercontent.com/linkerd/linkerd2/edge-%s/charts/linkerd-crds/templates"

var linkerdFiles = []string{
	"serviceprofile.yaml",
	"policy/server.yaml",
	"policy/server-authorization.yaml",
	"policy/authorization-policy.yaml",
	"policy/meshtls-authentication.yaml",
	"policy/network-authentication.yaml",
	"policy/egress-network.yaml",
	"policy/http-local-ratelimit-policy.yaml",
	"workload/external-workload.yaml",
}

var linkerdExpected = []string{
	"serviceprofiles.linkerd.io",
	"servers.policy.linkerd.io",
	"serverauthorizations.policy.linkerd.io",
	"authorizationpolicies.policy.linkerd.io",
	"meshtlsauthentications.policy.linkerd.io",
	"networkauthentications.policy.linkerd.io",
	"egressnetworks.policy.linkerd.io",
	"httplocalratelimitpolicies.policy.linkerd.io",
	"externalworkloads.workload.linkerd.io",
}

var upstreamMeta = regexp.MustCompile(`  annotations:\n` +
	`    \{\{ include "partials\.annotations\.created-by" \. \}\}\n` +
	`  labels:\n` +
	`    helm\.sh/chart: \{\{ \.Chart\.Name \}\}-\{\{ \.Chart\.Version \| replace "\+" "_" \}\}\n` +
	`    linkerd\.io/control-plane-ns: \{\{\.Release\.Namespace\}\}\n`)

const ourMeta = `  annotations:
    {{- if .Values.crds.keep }}
    helm.sh/resource-policy: keep
    {{- end }}
  labels:
    helm.sh/chart: {{ .Chart.Name }}-{{ .Chart.Version }}
    app.kubernetes.io/name: {{ .Chart.Name }}
    app.kubernetes.io/managed-by: {{ .Release.Service }}
    linkerd.io/control-plane-ns: {{ .Release.Namespace }}
`

const linkerdHeader = `{{- /* GENERATED by qw gen-linkerd-crds (charts/tools/qw), do not hand-edit.

     The linkerd-ONLY CustomResourceDefinitions from linkerd/linkerd2
     charts/linkerd-crds, at the appVersion this chart declares. Each CRD spec
     is upstream's, byte for byte; only the metadata annotations and labels are
     this chart's, so no upstream library chart is required.

     Upstream's bundle also carries the Gateway API route CRDs. Those are NOT
     here on purpose: quench/gateway-api-crds owns those names, and a
     cluster-scoped CRD with two owners belongs to whichever applied last.

     Re-run the generator to update; the release workflow runs it with --check
     and refuses to publish when this file and upstream disagree. */}}
`

func genLinkerdCRDs(ver string) (string, error) {
	out := []string{linkerdHeader}
	seen := map[string]bool{}
	nameRe := regexp.MustCompile(`(?m)^  name: (\S+)$`)
	for _, f := range linkerdFiles {
		url := fmt.Sprintf(linkerdBase, ver) + "/" + f
		b, err := core.FetchURL(url)
		if err != nil || strings.TrimSpace(string(b)) == "" {
			return "", fmt.Errorf("!! could not fetch %s", url)
		}
		body := string(b)
		if !upstreamMeta.MatchString(body) {
			return "", fmt.Errorf("!! %s: upstream metadata block did not match; the shape changed, re-read it before regenerating", f)
		}
		body = upstreamMeta.ReplaceAllLiteralString(body, ourMeta)
		m := nameRe.FindStringSubmatch(body)
		if m == nil {
			return "", fmt.Errorf("!! %s: no CRD name found", f)
		}
		seen[m[1]] = true
		if strings.Contains(body, "{{ include") || strings.Contains(body, "partials.") {
			return "", fmt.Errorf("!! %s: an upstream library reference survived the rewrite", f)
		}
		if !strings.HasPrefix(body, "---") {
			body = "---\n" + body
		}
		out = append(out, body)
	}
	var missing, extra []string
	want := map[string]bool{}
	for _, n := range linkerdExpected {
		want[n] = true
		if !seen[n] {
			missing = append(missing, n)
		}
	}
	for n := range seen {
		if !want[n] {
			extra = append(extra, n)
		}
	}
	if len(missing)+len(extra) > 0 {
		sort.Strings(missing)
		sort.Strings(extra)
		return "", fmt.Errorf("!! CRD set changed. missing=%v unexpected=%v", missing, extra)
	}
	return strings.Join(out, ""), nil
}

func Linkerd(args []string) int {
	check := false
	var pos []string
	for _, a := range args {
		if a == "--check" {
			check = true
		} else if !strings.HasPrefix(a, "--") {
			pos = append(pos, a)
		}
	}
	if len(pos) == 0 {
		fmt.Println("usage: qw gen-linkerd-crds <edge-version> [--check]")
		return 2
	}
	ver := pos[0]
	target := filepath.Join(core.ChartsRoot, "quench", "linkerd-crds", "templates", "crds.yaml")
	gen, err := genLinkerdCRDs(ver)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	if check {
		cur, err := os.ReadFile(target)
		if err != nil {
			fmt.Printf("!! %s does not exist\n", target)
			return 1
		}
		if string(cur) != gen {
			fmt.Printf("!! %s differs from upstream edge-%s; re-run the generator\n", target, ver)
			return 1
		}
		fmt.Printf("ok crds.yaml matches linkerd2 edge-%s (%d CRDs)\n", ver, len(linkerdExpected))
		return 0
	}
	if err := os.WriteFile(target, []byte(gen), 0o644); err != nil {
		fmt.Println(err)
		return 2
	}
	fmt.Printf("wrote %s from linkerd2 edge-%s: %d CRDs, %d bytes\n", target, ver, len(linkerdExpected), len(gen))
	return 0
}
