package gencrds

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/quenchworks/charts/tools/qw/internal/core"
	"gopkg.in/yaml.v3"
)

var promCRDs = []string{"alertmanagerconfigs", "alertmanagers", "podmonitors", "probes", "prometheusagents",
	"prometheuses", "prometheusrules", "scrapeconfigs", "servicemonitors", "thanosrulers"}

// stripDescriptions drops every "description" key under openAPIV3Schema. A field that is
// itself NAMED description (inside a properties map) is kept: only schema annotations go.
func stripDescriptions(n *yaml.Node, inProperties bool) {
	switch n.Kind {
	case yaml.DocumentNode, yaml.SequenceNode:
		for _, c := range n.Content {
			stripDescriptions(c, false)
		}
	case yaml.MappingNode:
		var keep []*yaml.Node
		for i := 0; i < len(n.Content); i += 2 {
			k, v := n.Content[i], n.Content[i+1]
			if k.Value == "description" && !inProperties && v.Kind == yaml.ScalarNode {
				continue
			}
			stripDescriptions(v, k.Value == "properties")
			keep = append(keep, k, v)
		}
		n.Content = keep
	}
}

func genPromCRDs(ver string) (string, error) {
	var out bytes.Buffer
	out.WriteString("# GENERATED by qw gen-prometheus-crds (charts/tools/qw) from prometheus-operator v" + ver + ",\n" +
		"# schema descriptions removed so the set fits Helm's 1 MiB release Secret. Do not hand-edit.\n")
	for _, c := range promCRDs {
		url := "https://raw.githubusercontent.com/prometheus-operator/prometheus-operator/v" + ver +
			"/example/prometheus-operator-crd/monitoring.coreos.com_" + c + ".yaml"
		b, err := core.FetchURL(url)
		if err != nil {
			return "", err
		}
		var doc yaml.Node
		if err := yaml.Unmarshal(b, &doc); err != nil {
			return "", fmt.Errorf("%s: %v", c, err)
		}
		stripDescriptions(&doc, false)
		out.WriteString("---\n")
		enc := yaml.NewEncoder(&out)
		enc.SetIndent(2)
		if err := enc.Encode(&doc); err != nil {
			return "", err
		}
		enc.Close()
	}
	return out.String(), nil
}

func Prometheus(args []string) int {
	check := false
	var pos []string
	for _, a := range args {
		if a == "--check" {
			check = true
		} else if !strings.HasPrefix(a, "--") {
			pos = append(pos, a)
		}
	}
	if len(pos) == 0 {
		fmt.Println("usage: qw gen-prometheus-crds <version> [--check]")
		return 2
	}
	gen, err := genPromCRDs(strings.TrimPrefix(pos[0], "v"))
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	target := filepath.Join(core.ChartsRoot, "quench", "prometheus-operator", "crds", "crds.yaml")
	if check {
		cur, _ := os.ReadFile(target)
		if string(cur) != gen {
			fmt.Printf("!! %s differs from prometheus-operator v%s; re-run the generator\n", target, pos[0])
			return 1
		}
		fmt.Printf("ok crds.yaml matches prometheus-operator v%s (%d CRDs)\n", pos[0], len(promCRDs))
		return 0
	}
	if err := os.WriteFile(target, []byte(gen), 0o644); err != nil {
		fmt.Println(err)
		return 2
	}
	fmt.Printf("wrote %s: %d CRDs, %d bytes\n", target, len(promCRDs), len(gen))
	return 0
}
